// Turns the picked hubs into src/data/gatewaysBulk.ts (compact) and prints a review report.
//   node write-bulk.mjs <work-dir> <positions.json> <state-bus.json|-> <app-root> [--write]
import fs from "node:fs";
const [, , WORK, POS, STATEBUS, APP] = process.argv;
const WRITE = process.argv.includes("--write");
const picked = JSON.parse(fs.readFileSync(`${WORK}/picked.json`, "utf8"));
const positions = new Map(JSON.parse(fs.readFileSync(POS, "utf8")).map((p) => [p.id, p]));
const stateBus = STATEBUS && STATEBUS !== "-" && fs.existsSync(STATEBUS) ? JSON.parse(fs.readFileSync(STATEBUS, "utf8")) : {};
const verified = fs.existsSync(`${WORK}/airports_verified.json`) ? JSON.parse(fs.readFileSync(`${WORK}/airports_verified.json`, "utf8")) : {};
const stationFixes = fs.existsSync(`${WORK}/station_fixes.json`) ? JSON.parse(fs.readFileSync(`${WORK}/station_fixes.json`, "utf8")) : {};
const reviewed = new Set((await import(`${APP}/src/data/gateways.ts`)).GATEWAYS ? Object.keys((await import(`${APP}/src/data/gateways.ts`)).GATEWAYS) : []);

const AIR = {}, RAIL = {}, BUS = {}, STATE = {}, PLACES = {};
const skipped = [], unverifiedUsed = new Map(), stats = { places: 0, air: 0, rail: 0, bus: 0, busTown: 0, railNone: 0 };
const cap = (s) => s.replace(/\s+/g, " ").trim();

for (const [id, r] of Object.entries(picked)) {
  if (reviewed.has(id)) continue; // hand-checked entries win
  const pos = positions.get(id);
  const why = [];
  if (!pos?.coord) { skipped.push([id, "no usable position"]); continue; }
  let air = r.air, rail = r.rail, bus = r.bus;
  // rail: a station whose code could not be confirmed is only used if someone has fixed it
  rail = rail.map((s) => {
    if (!s.unverified) return s;
    const fix = stationFixes[s.code];
    if (!fix) { (unverifiedUsed.get(s.code) ?? unverifiedUsed.set(s.code, { name: s.name, places: [] }).get(s.code)).places.push(id); return null; }
    return fix.ok === false ? null : { ...s, code: fix.code ?? s.code, name: fix.name ?? s.name };
  }).filter(Boolean);
  rail = rail.filter((x, i) => rail.findIndex((y) => y.code === x.code) === i); // a fixed code can collide with one already listed
  if (!air.length && !rail.length && !bus.length && !r.busTown) { skipped.push([id, "no airport, station or bus station within reach by road"]); continue; }
  if (air.some((a) => a.km > 700) ) air = air.filter((a) => a.km <= 700);
  const st = pos.state;
  const sb = stateBus[st];
  const row = { s: st };
  if (air.length) { row.a = air.map((a) => [a.iata, a.km, a.minutes]); for (const a of air) {
    const v = verified[a.iata];
    const note = a.service === "few" ? "Few flights land here. Check your dates first." : null;
    const seasonal = v?.service === "seasonal" ? `Flights run only part of the year${v.note ? `. ${cap(v.note)}` : ""}.`.replace(/\.\./g, ".") : null;
    AIR[a.iata] = [a.name.replace(/ (International )?Airport$/i, (m) => m).replace(/\s+/g, " "), a.service, (v?.area && cap(v.area)) || (a.city ? "" : ""), seasonal ?? note ?? ""]; } }
  if (rail.length) { row.r = rail.map((s) => [s.code, s.km, s.minutes]); for (const s of rail) {
    const small = s.trains < 20 && !s.unknownTrains;
    const note = s.renamedFrom ? `Formerly ${s.renamedFrom}. Search for ${s.code}.` : s.unknownTrains ? "A newer or little-used station. Check that trains stop here." : small ? "A small station. Only some trains stop here. Check that your train stops here." : "";
    RAIL[s.code] = [s.name, s.junction ? 1 : 0, "", note]; } }
  if (rail.length && rail[0].km > 100) { row.rn = 1; stats.railNone++; }
  if (bus.length) { row.b = bus.map((b) => [b.id, b.km, b.minutes]); for (const b of bus) BUS[b.id] = [b.name, ""]; }
  else if (r.busTown) { row.t = [r.busTown.name, r.busTown.km, r.busTown.minutes]; stats.busTown++; }
  if (sb && !STATE[st]) STATE[st] = [sb.short ?? sb.corporation ?? "", sb.bookingUrl ?? ""];
  PLACES[id] = row;
  stats.places++; stats.air += air.length ? 1 : 0; stats.rail += rail.length ? 1 : 0; stats.bus += bus.length ? 1 : 0;
}

const q = JSON.stringify;
const obj = (o) => "{\n" + Object.keys(o).sort().map((k) => `  ${q(k)}: ${q(o[k])},`).join("\n") + "\n}";
const ts = `// GENERATED by scripts/gateways/bulk/write-bulk.mjs from open data. Do not edit by hand: re-run the script.
//
// "Gateways" worked out for places a person has not reviewed by hand (see gateways.ts for those). They
// come from open data and are shown with a plain warning (basis: "mapdata"):
//   - airports:  OurAirports + the Airports Authority of India traffic table, each checked against
//                current airline / airport sources for scheduled flights;
//   - stations:  Datameet railway data (stations and a 2016 timetable, used only to count trains),
//                with codes cross-checked against Wikidata's current Indian Railways codes;
//   - bus:       OpenStreetMap bus stations (names only; who runs the buses is not known);
//   - roads:     OpenStreetMap routing (OSRM), times scaled for Indian roads.
// Hubs are stored once and places point at them: [hub id, road km, road minutes].
import type { AirService, GatewayAir, GatewayBus, GatewayRail, PlaceGateways } from "./gateways";

const CHECKED = "Oct 2026";
const AIR: Record<string, [name: string, service: AirService, area: string, note: string]> = ${obj(AIR)};
const RAIL: Record<string, [name: string, junction: 0 | 1, area: string, note: string]> = ${obj(RAIL)};
const BUS: Record<string, [name: string, area: string]> = ${obj(BUS)};
const STATE_BUS: Record<string, [operatorName: string, bookingUrl: string]> = ${obj(STATE)};

type Hop = [id: string, km: number, minutes: number];
interface Row { s: string; a?: Hop[]; r?: Hop[]; b?: Hop[]; rn?: 1; t?: [name: string, km: number, minutes: number] }
const PLACES: Record<string, Row> = ${obj(PLACES)};

export function getBulkGateways(destId: string): PlaceGateways | undefined {
  const row = PLACES[destId];
  if (!row) return undefined;
  const sb = STATE_BUS[row.s];
  const air: GatewayAir[] = (row.a ?? []).map(([id, km, minutes]) => {
    const [name, service, area, note] = AIR[id];
    return { name, code: id, area: area || undefined, km, minutes, service, note: note || undefined };
  });
  const rail: GatewayRail[] = (row.r ?? []).map(([id, km, minutes]) => {
    const [name, junction, area, note] = RAIL[id];
    return { name, code: id, area: area || undefined, km, minutes, junction: junction ? true : undefined, note: note || undefined };
  });
  const bus: GatewayBus[] = (row.b ?? []).map(([id, km, minutes]) => {
    const [name, area] = BUS[id];
    return { name, area: area || undefined, km, minutes, operator: "unknown", operatorName: sb?.[0] || undefined, bookingUrl: sb?.[1] || undefined };
  });
  return {
    checked: CHECKED,
    basis: "mapdata",
    air,
    rail,
    railNone: row.rn && rail[0] ? \`There is no railway close by. \${rail[0].name} is the nearest railhead.\` : undefined,
    bus,
    busTown: row.t ? { name: row.t[0], km: row.t[1], minutes: row.t[2] } : undefined,
  };
}

/** Every place id that has a generated entry (used by the data checker). */
export const BULK_IDS: string[] = Object.keys(PLACES);
`;
console.log(stats);
console.log("skipped:", skipped.length, skipped.slice(0, 8));
console.log("stations with unconfirmed codes that were left out:", [...unverifiedUsed.entries()].map(([c, v]) => `${c} (${v.name}, ${v.places.length} places)`).join("; "));
console.log("output size:", Math.round(ts.length / 1024), "KB");
if (WRITE) { fs.writeFileSync(`${APP}/src/data/gatewaysBulk.ts`, ts); console.log("wrote src/data/gatewaysBulk.ts"); }
fs.writeFileSync(`${WORK}/bulk-report.json`, JSON.stringify({ stats, skipped, unverified: [...unverifiedUsed.entries()] }));
